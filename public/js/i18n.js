let currentLang = localStorage.getItem("sakin_lang") || "tr";
const SUPPORTED_LANGS = [
  { code: "tr", label: "Türkçe" },
  { code: "de", label: "Deutsch" },
  { code: "ru", label: "Русский" },
  { code: "az", label: "Azərbaycanca" },
];

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.tr[key] || key;
}

// t() + basit {placeholder} degistirme - orn. tf("nav.noResultsFor", {q: "kasa"}).
function tf(key, vars) {
  let s = t(key);
  for (const k in vars || {}) s = s.split(`{${k}}`).join(vars[k]);
  return s;
}

// Dil degisince tum ekranin yeniden cizilmesi gerekir (t() cagrilari zaten
// render fonksiyonlarinin icinde calisti/bitti) - site degistirmede kullanilan
// ayni desen: basit bir tam sayfa yenilemesi, kismi state gecersiz kilmadan
// cok daha guvenli.
function setLang(code) {
  if (!I18N[code]) return;
  localStorage.setItem("sakin_lang", code);
  location.reload();
}

function langSelectHtml(extraAttrs) {
  return `<select class="lang-select" ${extraAttrs || ""}>${SUPPORTED_LANGS.map((l) => `<option value="${l.code}" ${l.code === currentLang ? "selected" : ""}>${l.label}</option>`).join("")}</select>`;
}
